#!/usr/bin/env bash
# =============================================================================
# Ghashem FinOps — One-time: store the SSO app credential in the company vault
# =============================================================================
# Run this ONCE, from your local machine, logged into your company Azure
# account (the one where the Ghashem app registration and kv-ghashem-company
# live).
#
# This replaces pasting AZURE_APP_CLIENT_ID / AZURE_APP_CLIENT_SECRET into
# every environment (local .env, App Service settings, etc.). Instead, every
# environment reads the same one secret from Key Vault via settings.py's
# _load_sso_credentials() function.
#
# Usage:
#   bash setup-sso-secret.sh
# =============================================================================

set -euo pipefail

COMPANY_KV="kv-ghashem-company"
SECRET_NAME="ghashem-sso-app-secret"

echo ""
echo "=== Storing the Ghashem SSO app credential in $COMPANY_KV ==="
echo ""
echo "Find these two values at:"
echo "  portal.azure.com → Azure Active Directory → App registrations"
echo "  → [your Ghashem app] → Overview (Client ID)"
echo "  → Certificates & secrets (Client secret — only shown once at creation)"
echo ""

read -rp "App registration Client ID: " CLIENT_ID
read -rsp "App registration Client Secret: " CLIENT_SECRET
echo ""

if [ -z "$CLIENT_ID" ] || [ -z "$CLIENT_SECRET" ]; then
  echo "✗ Both values are required. Aborting."
  exit 1
fi

# Stored as "client_id:client_secret" — settings.py splits on the first colon.
# Client secrets generated by Azure AD never contain a colon, so this is safe.
COMBINED="${CLIENT_ID}:${CLIENT_SECRET}"

echo "→ Creating $COMPANY_KV if it doesn't already exist..."
az keyvault create \
  --name "$COMPANY_KV" \
  --resource-group "rg-ghashem-company" \
  --location "canadacentral" \
  --output none 2>/dev/null || echo "  (already exists — skipping)"

echo "→ Storing secret..."
az keyvault secret set \
  --vault-name "$COMPANY_KV" \
  --name "$SECRET_NAME" \
  --value "$COMBINED" \
  --output none

echo ""
echo "✓ Stored. Every environment (local, dev, prod) will now read this"
echo "  automatically via COMPANY_VAULT_URL, as long as:"
echo "  1. COMPANY_VAULT_URL=https://${COMPANY_KV}.vault.azure.net/ is set"
echo "  2. The App Service's Managed Identity (or your local az login)"
echo "     has get/list permission on $COMPANY_KV"
echo ""
echo "Run 01-provision.sh next — it grants the App Service access automatically."
